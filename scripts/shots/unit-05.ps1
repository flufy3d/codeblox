# ══ 单元 5「逻辑与重复」的视口场景 ══════════════════════════════
# 坐标都是场景局部坐标：X 左右、Y 上下、Z 前后，原点在地面。
# ⚠️ 局部 +X 在画面**左**边；局部 −Z 是**朝镜头**这一侧。
#
# 这个单元有三组「同机位对比图」，是它跟前面几个单元最大的不同：
#   5.3-s2/s3  同一个方块，两种颜色      —— 讲 while 在替你重复
#   5.4-s2/s3  同一条跑道，5 格 vs 10 格 —— 讲 for 只改一个数就变长
#   5.5-s2/s3  同一条跑道，两套随机色    —— 讲 math.random 每次都不一样
# 每组两张的 lp/d/yaw/pitch **必须一模一样**，孩子上下滚页面才能一眼读出
# 「哪儿变了」。换机位这三组就白拍了。
#
# 5.4 / 5.5 / 5.8 共用同一条跑道的几何（$U5ROAD10），只是材质/颜色不同 ——
# 课文里也确实是同一段代码一路改出来的，图跟着这么走才对得上。
#
# 用法：
#   . ".claude\skills\studio-shots\lib\load.ps1"
#   . "scripts\shots\unit-05.ps1"
#   Shoot-Batch $U5 'sheet-u5' 2 -Verify

# ── 公共片段 ─────────────────────────────────────────────────

# 把小人挪到地图底下。没有小人的那 7 张要先赶走它，否则它会站在上一张的位置入镜。
# ⚠️ y=-400，别挪到 (0,0,0)：那儿离场景原点 (150,0,0) 不算远，广角照样拍得到。
$U5PARK = 'local r=ws:FindFirstChild("Rig") if r then r:PivotTo(CFrame.new(0,-400,0)) end '

# 跑道：10 个 4×1×4 的格子，间隔 5，浮在 y=5。
# 课文里是 Position = Vector3.new(i * 5, 5, 0)，即 x 从 5 排到 50；这里整体平移
# 到以 0 为中心，好让对准点就是画面正中。
# ⚠️ x 用 22.5-(i-1)*5 递**减**，不是 (i-1)*5-22.5 递增：局部 +X 在画面左边，
#    而斜角构图下画面左边是**离镜头近**的那一头（格子大）。递增的话 i=1..5 会落在
#    右边那个又远又小的半截上，5.4-s2「5 个格子」就成了一排看不清的小点 ——
#    第一版就是这么拍的。递减之后 5 格那张占的是左边又大又清楚的半边。
#   $N    造几个格子（5.4-s2 只造 5 个，其余 10 个）
#   $Mat  材质（5.4 是默认塑料，5.5/5.8 是 Neon）
#   $Seed 随机色种子；给 0 就不上色（保持默认灰）
function Road([int]$N = 10, [string]$Mat = 'nil', [int]$Seed = 0) {
  # ⚠️ 局部变量别叫 $seed —— PowerShell 不分大小写，会跟参数 $Seed 撞上，
  #    赋字符串给 [int] 参数直接报 InvalidArgument。
  $col = if ($Seed -gt 0) { ',Color3.fromRGB(math.random(1,255),math.random(1,255),math.random(1,255))' } else { '' }
  $sd  = if ($Seed -gt 0) { "math.randomseed($Seed) " } else { '' }
  $sd + "for i=1,$N do P(`"R`"..i,Vector3.new(4,1,4),Vector3.new(22.5-(i-1)*5,5,0),$Mat$col) end "
}

# 跑道类的机位。⚠️ 一排 49 studs 长的东西，斜角必须收窄（yaw 194，离正对只有
# 14°）—— 默认的 210 会让最近那格被透视放大到出画面。d=25 是按「可见宽度≈2.5d」
# 反推的（49 需要 ≥20），再留一点余量给近端的透视放大。
# pitch 22 是为了看到格子的**顶面**：这些格子只有 1 厚，俯角低了就只剩一条线。
$U5ROADCAM = @{ lp = 'Vector3.new(0,5,0)'; d = 25; yaw = 194; pitch = 22 }

# 熔岩：16×1×16 的红色塑料板，贴地。课文第 1 步就是让孩子把 Size 改成 16,1,16、
# 到「主页 → 颜色」挑红色 —— 用 PN（真名 Lava）好让它在别的图里也是同一块东西。
$U5LAVA = 'PN("Lava",Vector3.new(16,1,16),Vector3.new(0,0.5,0),M.Plastic,Color3.fromRGB(196,40,28)) '

$U5 = [ordered]@{}

# ── 5.3 while：一个方块自己换颜色 ───────────────────────────
# 两张同机位，只有颜色不同。绿 → 橙 拉得够开，缩到网页上也一眼看得出换了色。
# d=7：可见高度约 9.8，4×4×4 的方块占 41%，主体够大又不顶边。

$U5['5.3-s2'] = @{
  geo = $U5PARK + 'P("Block",Vector3.new(4,4,4),Vector3.new(0,2,0),M.Plastic,Color3.fromRGB(75,151,75)) '
  lp  = 'Vector3.new(0,2,0)'; d = 7
}

$U5['5.3-s3'] = @{
  geo = $U5PARK + 'P("Block",Vector3.new(4,4,4),Vector3.new(0,2,0),M.Plastic,Color3.fromRGB(218,133,65)) '
  lp  = 'Vector3.new(0,2,0)'; d = 7
}

# ── 5.4 for：5 格 → 10 格 ────────────────────────────────────
# 关键：两张**同一个机位**，5 格的那张只占半边、另半边空着。这样「只改一个数字，
# 跑道长了一倍」是图自己讲出来的，不用靠文字说。
# 局部 +X 在画面左边 → i=1 在最右，i=10 在最左，5 格那张东西堆在画面右半边。

$U5['5.4-s2'] = @{ geo = $U5PARK + (Road 5) }  + $U5ROADCAM
$U5['5.4-s3'] = @{ geo = $U5PARK + (Road 10) } + $U5ROADCAM

# ── 5.5 math.random：同一条跑道，两套随机色 ──────────────────
# 用 randomseed 固定两个不同的种子，而不是硬编码调好看的颜色 —— 图上出现的
# 就是课文那行 math.random(1,255) 真会抽出来的东西。
# 种子是挑过的：随机 RGB 常抽出接近白/黑的闷色，一排下来就不像「彩虹」了
# （42 抽出来大半是白和浅粉，3 里有一块纯黑）。7 和 55 这两套既鲜艳、彼此又
# 完全不撞色，放在一起最能说明「每次都不一样」。换种子重跑就能换一套。

$U5['5.5-s2'] = @{ geo = $U5PARK + (Road 10 'M.Neon' 7)  } + $U5ROADCAM
$U5['5.5-s3'] = @{ geo = $U5PARK + (Road 10 'M.Neon' 55) } + $U5ROADCAM

# ── 5.6 熔岩 ─────────────────────────────────────────────────

# 5.6-s1 · 空的红色熔岩板
# pitch 26 / d=17：又是一块贴地的扁板子，跟 4.3-s1 一个道理 —— 俯角要够高才读得出
# 它是「摊开的一片」而不是一条边，距离要够远才不会四个角被透视顶出画面
# （16 宽的板子按 2.5d 算 d=7 就「够」，实际得退到 17 才四边都留出余量）。
$U5['5.6-s1'] = @{
  geo = $U5PARK + $U5LAVA
  lp  = 'Vector3.new(0,0.5,0)'; d = 17; pitch = 26
}

# 5.6-s3 · 小人站上去了
# 板顶面 y=1（中心 0.5 + 厚 1 的一半），所以 Rig-At 的 y 给 1。
# d=11 让红色占满大半个画面 —— 这张要的是「他正站在熔岩上」的紧张感，
# 退太远就变成一块红地毯配个小人。
$U5['5.6-s3'] = @{
  geo = $U5LAVA + (Rig-At 'Vector3.new(0,1,0)' 15)
  lp  = 'Vector3.new(0,2.6,0)'; d = 11
}

# ── 5.8 单元成果全景：跑道 + 熔岩 + 人 ───────────────────────
# 这两张也是一组同机位对比：人在跑道上 → 人踩进熔岩。
#
# 构图上最难的一张：要同时装下 49 长的跑道、一块熔岩、还有一个只有 5.5 高的小人，
# 一味退远小人就成了一个点（第一版 d=27 就是这样，人小到看不出在干嘛）。
# 解法是把三样东西都往**画面左边那个离镜头近的角**挤：熔岩挪到跑道左半截的
# 斜下方，小人站在跑道左端第 2 格 —— 那一头透视放大，人和熔岩都够大；跑道右半截
# 往画面深处收，正好交代「这条道很长」。
#
# ⚠️ 对准点的 z 要落在跑道(z=0)和熔岩之间，不能贴着熔岩的远边：熔岩是往**镜头这
#    一侧**长的（局部 -Z 朝镜头），对准点压在它远边上，它整块就会往画面下方溢出去，
#    底边被切掉（第一版 lp z=-5 配 d=23 就是这样）。现在 lp 取 z=-7、d 退到 27。
$U5SCENE = 'PN("Lava",Vector3.new(16,1,12),Vector3.new(9,0.5,-11),M.Plastic,Color3.fromRGB(196,40,28)) ' +
           (Road 10 'M.Neon' 7)
$U5SCENECAM = @{ lp = 'Vector3.new(4,3,-7)'; d = 27; yaw = 200; pitch = 25 }

# 站在跑道上：格子中心 y=5、厚 1 → 顶面 y=5.5。x=17.5 是左起第 2 格。
$U5['5.8-s2'] = @{ geo = $U5SCENE + (Rig-At 'Vector3.new(17.5,5.5,0)' 15) } + $U5SCENECAM

# 踩进熔岩：熔岩顶面 y=1，站在靠镜头这一侧，人才够大。
$U5['5.8-s3'] = @{ geo = $U5SCENE + (Rig-At 'Vector3.new(11,1,-13)' 15) } + $U5SCENECAM
