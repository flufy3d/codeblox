# ══ 单元 6「玩家与分数」的视口场景 ══════════════════════════════
# 坐标都是场景局部坐标：X 左右、Y 上下、Z 前后，原点在地面。
# ⚠️ 局部 +X 在画面**左**边；局部 −Z 是**朝镜头**这一侧。
#
# 这个单元只有 2 张纯视口图（6.5-s1 一块垫子 / 6.8-s2 一排垫子），
# 大头在 unit-06-ui.ps1：代码、输出、资源管理器，以及**这个单元独有的
# 「试玩画面里的计分板」**——那些必须真进 Play 模式才拍得到。
#
# 得分垫的规格跟课文 6.5 一字对应：6×1×6 压扁、亮黄色、Anchored。
# 用 PN（真名 Pad）而不是 P，因为 6.8-s1 要在资源管理器里右键它，
# 树上得显示给孩子看的真名。
#
# 用法：
#   . ".claude\skills\studio-shots\lib\load.ps1"
#   . "scripts\shots\unit-06.ps1"
#   Shoot-Batch $U6 'sheet-u6' 2 -Verify

# ── 公共片段 ─────────────────────────────────────────────────

# 把小人挪到地图底下。6.5-s1 没有小人，得先赶走它，否则它会站在上一张的位置入镜。
# ⚠️ y=-400，别挪到 (0,0,0)：那儿离场景原点 (150,0,0) 不算远，广角照样拍得到。
$U6PARK = 'local r=ws:FindFirstChild("Rig") if r then r:PivotTo(CFrame.new(0,-400,0)) end '

# 一块得分垫。$Lp 是局部坐标，垫子中心抬到 y=0.5 → 顶面正好 y=1（摆小人时用得上）。
# 亮黄色 (245,205,48) 对应课文说的「主页 → 颜色 挑个亮眼的」。
function Pad([string]$Name, [double]$X) {
  "PN(`"$Name`",Vector3.new(6,1,6),Vector3.new($X,0.5,0),M.Plastic,Color3.fromRGB(245,205,48)) "
}

$U6 = [ordered]@{}

# ── 6.5 一块得分垫 ───────────────────────────────────────────
# 又是一块贴地的扁板子，跟 5.6-s1 一个道理：俯角要够高（26）才读得出它是
# 「摊开的一片」而不是一条边；距离要够远才不会四个角被透视顶出画面。
# 6 宽的板子按「可见宽度≈2.5d」算 d=2.4 就「够」，但那样它会顶满整幅、
# 看不出是放在地面上的 —— d=8 留出一圈灰地面当参照。
$U6['6.5-s1'] = @{
  geo = $U6PARK + (Pad 'Pad' 0)
  lp  = 'Vector3.new(0,0.5,0)'; d = 8; pitch = 26
}

# ── 6.8 一条收集路线 ─────────────────────────────────────────
# 5 块垫子排一排，间隔 9（垫子 6 宽 → 中间留 3 的缝，一眼看得出是「一块块」
# 而不是一条长板）。整排 4×9+6 = 42 studs 长。
#
# ⚠️ x 用 18-(i-1)*9 递**减**，不是递增：局部 +X 在画面左边，而斜角构图下
#    画面左边是**离镜头近**的那一头。第 1 块落在左边才又大又清楚 —— 单元 5
#    的跑道图就是在这儿栽过一次（递增拍出来是右边又远又小的半排）。
#
# 一排 42 长的东西，斜角必须收窄：yaw=196（离正对只有 16°），默认的 210
# 会让最近那块被透视放大到出画面。d=22 是按 42/2.5≈17 再留余量反推的。
# pitch 24 是为了看到垫子的**顶面**：只有 1 厚，俯角低了就只剩一条线。
$U6ROUTE = ((1..5 | ForEach-Object { Pad "Pad$_" (18 - ($_ - 1) * 9) }) -join '')
$U6ROUTECAM = @{ lp = 'Vector3.new(0,1,0)'; d = 22; yaw = 196; pitch = 24 }

# 小人站在左起第 2 块上（x=9）。垫子顶面 y=1，所以 Rig-At 的 y 给 1。
# 站第 2 块而不是第 1 块：第 1 块在画面最左边缘，人站上去会被画框切掉半个。
# TurnDeg 200 ≈ 侧对镜头、面朝这排垫子延伸的方向，像正要往下一块走。
$U6['6.8-s2'] = @{ geo = $U6ROUTE + (Rig-At 'Vector3.new(9,1,0)' 200) } + $U6ROUTECAM
